/**
 * Minimal OBJ reader — enough to round-trip our own output and to ingest a mesh
 * a user drops in. Triangulates convex polygons with a fan; ignores groups,
 * smoothing, and materials beyond recording which was active.
 */
export function readObj(text: string): Mesh {
  const positions: number[] = [];
  const colors: number[] = [];
  const uvs: number[] = [];
  const normals: number[] = [];
  const indices: number[] = [];
  // OBJ lets a face reference position/uv/normal at different indices. We flatten
  // to one array per unique combination, which is what GPUs need anyway.
  const vertexMap = new Map<string, number>();
  const outPositions: number[] = [];
  const outColors: number[] = [];
  const outUvs: number[] = [];
  const outNormals: number[] = [];
  let sawColor = false;

  // OBJ indices are 1-based; a negative index counts back from the end of the
  // list *as it stands at that point in the file*, so `count` is passed in.
  const resolve = (index: number, count: number): number =>
    index < 0 ? count + index : index - 1;

  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (line === '' || line.startsWith('#')) continue;
    const parts = line.split(/\s+/);
    switch (parts[0]) {
      case 'v':
        positions.push(Number(parts[1]), Number(parts[2]), Number(parts[3]));
        if (parts.length >= 7) {
          sawColor = true;
          colors.push(Number(parts[4]), Number(parts[5]), Number(parts[6]));
        } else {
          colors.push(1, 1, 1);
        }
        break;
      case 'vt':
        uvs.push(Number(parts[1]), 1 - Number(parts[2]));
        break;
      case 'vn':
        normals.push(Number(parts[1]), Number(parts[2]), Number(parts[3]));
        break;
      case 'f': {
        const corners: number[] = [];
        for (let i = 1; i < parts.length; i++) {
          const token = parts[i];
          let index = vertexMap.get(token);
          if (index === undefined) {
            const [pRaw, tRaw, nRaw] = token.split('/');
            const p = resolve(Number(pRaw), positions.length / 3);
            outPositions.push(positions[p * 3], positions[p * 3 + 1], positions[p * 3 + 2]);
            outColors.push(colors[p * 3], colors[p * 3 + 1], colors[p * 3 + 2]);
            if (tRaw) {
              const t = resolve(Number(tRaw), uvs.length / 2);
              outUvs.push(uvs[t * 2] ?? 0, uvs[t * 2 + 1] ?? 0);
            }
            if (nRaw) {
              const nIdx = resolve(Number(nRaw), normals.length / 3);
              outNormals.push(
                normals[nIdx * 3] ?? 0,
                normals[nIdx * 3 + 1] ?? 0,
                normals[nIdx * 3 + 2] ?? 0,
              );
            }
            index = outPositions.length / 3 - 1;
            vertexMap.set(token, index);
          }
          corners.push(index);
        }
        // Fan-triangulate. Correct for convex faces, which is what OBJ exporters emit.
        for (let i = 1; i + 1 < corners.length; i++) {
          indices.push(corners[0], corners[i], corners[i + 1]);
        }
        break;
      }
      default:
        break;
    }
  }

  const mesh: Mesh = {
    positions: Float32Array.from(outPositions),
    indices: Uint32Array.from(indices),
  };
  if (outNormals.length > 0) mesh.normals = Float32Array.from(outNormals);
  if (outUvs.length > 0) mesh.uvs = Float32Array.from(outUvs);
  if (sawColor) mesh.colors = Float32Array.from(outColors);
  return mesh;
}
