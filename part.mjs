import { readFileSync } from 'node:fs';
import { parse } from './dump.mjs';
const {nodes} = parse(new Uint8Array(readFileSync(process.argv[2]).buffer));
const show=(p)=>typeof p==='string'?JSON.stringify(p.length>40?p.slice(0,40)+'…':p):(p&&p.a?`${p.a}[${p.n}]`:(p&&p.raw!==undefined?`raw[${p.raw}]`:p));
function tree(ns,d,max,out){for(const n of ns){out.push('  '.repeat(d)+n.name+' '+n.props.map(show).join(' '));
if(d<max)tree(n.children,d+1,max,out);else if(n.children.length)out.push('  '.repeat(d+1)+'…'+n.children.length);}}
const find=(ns,f)=>{for(const x of ns){if(f(x))return x;const g=find(x.children,f);if(g)return g;}return null;};
const objects=nodes.find(n=>n.name==='Objects');
console.log('=== Definitions (ObjectType Model) ===');
const defs=nodes.find(n=>n.name==='Definitions');
const mt=defs.children.find(c=>c.name==='ObjectType'&&c.props[0]==='Model');
let out=[];tree([mt],0,2,out);console.log(out.slice(0,14).join('\n'));
console.log('\n=== a Mesh Geometry ===');
const geo=objects.children.find(c=>c.name==='Geometry'&&c.props[2]==='Mesh');
out=[];tree([geo],0,2,out);console.log(out.slice(0,30).join('\n'));
console.log('\n=== the Model that owns geometry ===');
const model=objects.children.find(c=>c.name==='Model'&&c.props[2]==='Mesh');
out=[];tree([model],0,2,out);console.log(out.slice(0,26).join('\n'));
console.log('\n=== a Material ===');
const mat=objects.children.find(c=>c.name==='Material');
out=[];tree([mat],0,1,out);console.log(out.slice(0,12).join('\n'));
console.log('\n=== object type histogram ===');
const h={};for(const c of objects.children)h[c.name]=(h[c.name]||0)+1;console.log(h);
const conns=nodes.find(n=>n.name==='Connections');
console.log('connections', conns.children.length, '| kinds', [...new Set(conns.children.map(c=>c.props[0]))].join(','));
